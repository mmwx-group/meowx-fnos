func TestChoose(t *testing.T) {
	fnos := Probe{NFTables: true, PolicyRouting: true, Legacy: -1, NFT: -1}
	if e := Choose("", "", "", fnos); e != (Env{Backend: NFTables}) {
		t.Fatalf("飞牛（scratch 镜像、有 nf_tables）应当照旧 nftables：%+v", e)
	}
	// 群晖：没有 nf_tables，只有 iptables-legacy
	syno := Probe{PolicyRouting: true, Legacy: 40, NFT: -1}
	if e := Choose("", "", "", syno); e.Backend != IPTables || e.IPTables != "legacy" || e.NoPolicyRouting {
		t.Fatalf("群晖：%+v", e)
	}
	if e := Choose("", "", "", Probe{Legacy: 0, NFT: -1}); !e.NoPolicyRouting || e.Backend != IPTables {
		t.Fatalf("没有策略路由：%+v", e)
	}
	// 有 nf_tables 但没有策略路由、镜像里有 iptables：走 iptables 的 REDIRECT 退化
	if e := Choose("", "", "", Probe{NFTables: true, Legacy: 0, NFT: 3}); e.Backend != IPTables || e.IPTables != "nft" || !e.NoPolicyRouting {
		t.Fatalf("%+v", e)
	}
	// 强制 iptables：跟着 Docker 的规则在哪套
	nftHost := Probe{NFTables: true, PolicyRouting: true, Legacy: 0, NFT: 120}
	if e := Choose("iptables", "", "", nftHost); e.Backend != IPTables || e.IPTables != "nft" {
		t.Fatalf("%+v", e)
	}
	if e := Choose("iptables", "legacy", "", nftHost); e.IPTables != "legacy" {
		t.Fatalf("%+v", e)
	}
	if e := Choose("nftables", "", "off", syno); e.Backend != NFTables || !e.NoPolicyRouting {
		t.Fatalf("%+v", e)
	}
	if e := Choose("", "", "on", Probe{Legacy: 1, NFT: -1}); e.NoPolicyRouting {
		t.Fatalf("on 应当当作有策略路由：%+v", e)
	}
}

func TestScript(t *testing.T) {
	var s Script
	if !s.Empty() || s.String() != "" {
		t.Fatal("空脚本")
	}
	s.Chain("nat", "MEOWX_A")
	s.Add("mangle", "-A MEOWX_B -j RETURN")
	s.Add("nat", "-A PREROUTING -j MEOWX_A")
	want := "*nat\n:MEOWX_A - [0:0]\n-A PREROUTING -j MEOWX_A\nCOMMIT\n*mangle\n-A MEOWX_B -j RETURN\nCOMMIT\n"
	if s.String() != want {
		t.Fatalf("%q", s.String())
	}
}

const sampleSave = `# Generated by iptables-save
*nat
:PREROUTING ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:DOCKER - [0:0]
:MEOWX_LAN - [0:0]
:MEOWX_MESH_PRE - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
-A PREROUTING -i eth0 -j MEOWX_LAN
-A PREROUTING -i eth1 -j MEOWX_LAN
-A PREROUTING -i tailscale0 -j MEOWX_MESH_PRE
-A MEOWX_LAN -p tcp -j REDIRECT --to-ports 7891
COMMIT
*filter
:FORWARD DROP [0:0]
:DOCKER-USER - [0:0]
:MEOWX_LAN_FWD - [0:0]
-A FORWARD -j DOCKER-USER
-A DOCKER-USER -j MEOWX_LAN_FWD
-A DOCKER-USER -j RETURN
-A MEOWX_LAN_FWD -i eth0 -o meowx -j ACCEPT
COMMIT
`

func TestCleanupCmds(t *testing.T) {
	got := CleanupCmds(sampleSave, "MEOWX_LAN")
	want := []Cmd{
		{"nat", []string{"-D", "PREROUTING", "-i", "eth0", "-j", "MEOWX_LAN"}},
		{"nat", []string{"-D", "PREROUTING", "-i", "eth1", "-j", "MEOWX_LAN"}},
		{"filter", []string{"-D", "DOCKER-USER", "-j", "MEOWX_LAN_FWD"}},
		{"nat", []string{"-F", "MEOWX_LAN"}},
		{"filter", []string{"-F", "MEOWX_LAN_FWD"}},
		{"nat", []string{"-X", "MEOWX_LAN"}},
		{"filter", []string{"-X", "MEOWX_LAN_FWD"}},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("\n得到 %v\n应当 %v", got, want)
	}
	if got := CleanupCmds(sampleSave, "MEOWX_HOST"); len(got) != 0 {
		t.Fatalf("没有就不动：%v", got)
	}
	if !ChainIn(sampleSave, "filter", "DOCKER-USER") || ChainIn(sampleSave, "nat", "DOCKER-USER") {
		t.Fatal("ChainIn")
	}
}

// 假的 iptables：记下跑过的命令，save 回固定内容
func TestIPTCleanupRuns(t *testing.T) {
	var ran []string
	run := func(stdin, name string, args ...string) (string, error) {
		ran = append(ran, name+" "+strings.Join(args, " "))
		if strings.HasSuffix(name, "-save") {
			return sampleSave, nil
		}
		return "", nil
	}
	if err := (IPT{Variant: "legacy", Run: run}).Cleanup("MEOWX_MESH"); err != nil {
		t.Fatal(err)
	}
	want := []string{
		"iptables-legacy-save ",
		"iptables-legacy -w 5 -t nat -D PREROUTING -i tailscale0 -j MEOWX_MESH_PRE",
		"iptables-legacy -w 5 -t nat -F MEOWX_MESH_PRE",
		"iptables-legacy -w 5 -t nat -X MEOWX_MESH_PRE",
	}
	if !reflect.DeepEqual(ran, want) {
		t.Fatalf("\n%q\n%q", ran, want)
	}
}
